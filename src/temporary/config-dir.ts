import fs from "node:fs/promises";
import { basename, dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

/** The extensions Storybook accepts for `main` (see `validateConfigurationFiles` in Storybook). */
export const MAIN_EXTENSIONS = [
  ".ts",
  ".mts",
  ".cts",
  ".tsx",
  ".js",
  ".mjs",
  ".cjs",
  ".jsx",
] as const;

/** Marks a config directory as written by the temporary mode, so it is safe to delete. */
export const MARKER_FILE = ".canvas-comments-temporary";

const MAIN_FILE_PATTERN = new RegExp(
  `^main(${MAIN_EXTENSIONS.map((extension) => extension.replace(".", "\\.")).join("|")})$`,
);

export const isMainFile = (name: string): boolean => MAIN_FILE_PATTERN.test(name);

/** Finds `main.*` in a Storybook config directory. */
export const findMainFile = async (configDir: string): Promise<string> => {
  let entries: string[];
  try {
    entries = await fs.readdir(configDir);
  } catch {
    throw new Error(
      `No Storybook config directory at ${configDir}. Run the command where Storybook runs, or pass --config-dir.`,
    );
  }
  const main = MAIN_EXTENSIONS.map((extension) => `main${extension}`).find(
    (name) => entries.includes(name),
  );
  if (!main) {
    throw new Error(`No main file (main.ts, main.js, ...) in ${configDir}.`);
  }
  return join(configDir, main);
};

/**
 * The temporary config directory sits next to the original one, at the same depth,
 * so paths in main that are relative to the config directory (`stories: ["../src/**"]`,
 * `staticDirs`) point at the same files.
 */
export const temporaryConfigDirFor = (configDir: string): string =>
  join(dirname(configDir), `${basename(configDir)}-canvas-comments`);

export type WrapperMainOptions = {
  /** The package directory of storybook-addon-canvas-comments, registered as the addon. */
  addonDir: string;
  /** Preset options for the addon. */
  addonOptions: Record<string, unknown>;
  /** Directories outside the project that Vite has to serve (the addon and its dependencies). */
  allowDirs: string[];
  /** The project's own main file. */
  mainFile: string;
};

/**
 * Generates a main file that loads the project's main and registers the addon on top of it.
 * It is ESM (`.mjs`) whatever the project's main is: Storybook imports it, and Storybook's
 * loader lets it import a TypeScript or CommonJS main.
 */
export const createWrapperMain = ({
  addonDir,
  addonOptions,
  allowDirs,
  mainFile,
}: WrapperMainOptions): string => `// Generated by \`npx storybook-addon-canvas-comments\` (temporary mode).
// It is deleted when Storybook exits. Do not edit or commit it.
import * as projectMain from ${JSON.stringify(pathToFileURL(mainFile).href)};

const ADDON_NAME = "storybook-addon-canvas-comments";
const addon = {
  name: ${JSON.stringify(addonDir)},
  options: ${JSON.stringify(addonOptions)},
};
const allowDirs = ${JSON.stringify(allowDirs)};

const config = projectMain.default ?? projectMain;
const addonName = (entry) => (typeof entry === "string" ? entry : entry?.name ?? "");
const registered = (config.addons ?? []).some((entry) =>
  addonName(entry).includes(ADDON_NAME),
);
if (registered) {
  console.warn(
    \`[canvas-comments] \${ADDON_NAME} is already in the addons of your main config, so the temporary mode adds nothing.\`,
  );
}

export default {
  ...config,
  addons: registered ? config.addons : [...(config.addons ?? []), addon],
  viteFinal: async (viteConfig, options) => {
    const resolved = config.viteFinal
      ? await config.viteFinal(viteConfig, options)
      : viteConfig;
    if (registered) {
      return resolved;
    }
    // Imported from this file, so it is the project's own Vite.
    const { mergeConfig, searchForWorkspaceRoot } = await import("vite");
    return mergeConfig(resolved, {
      // The addon runs from the npx cache. Its preview code imports "storybook/*",
      // which has to be the project's copy, not one installed next to the addon.
      resolve: { dedupe: ["storybook"] },
      server: {
        fs: {
          // Setting fs.allow replaces Vite's default, so keep the workspace root.
          allow: [
            ...(resolved.server?.fs?.allow
              ? []
              : [searchForWorkspaceRoot(resolved.root ?? process.cwd())]),
            ...allowDirs,
          ],
        },
      },
    });
  },
};
`;

const linkEntry = async (target: string, path: string, isDirectory: boolean) => {
  try {
    await fs.symlink(target, path, isDirectory ? "junction" : "file");
  } catch (error) {
    // Windows needs a privilege for file symlinks, but not for hard links.
    if (isDirectory) {
      throw error;
    }
    await fs.link(target, path);
  }
};

export type PrepareOptions = Omit<WrapperMainOptions, "mainFile"> & {
  configDir: string;
};

/**
 * Writes the temporary config directory: the wrapper main, plus a link to every other
 * file of the original config directory (preview, manager, preview-head.html, ...).
 * Returns its path.
 */
export const prepareTemporaryConfigDir = async ({
  configDir: rawConfigDir,
  ...options
}: PrepareOptions): Promise<string> => {
  const configDir = resolve(rawConfigDir);
  const mainFile = await findMainFile(configDir);
  const temporaryDir = temporaryConfigDirFor(configDir);

  // A run that was killed can leave its directory behind.
  await removeTemporaryConfigDir(temporaryDir);
  await fs.mkdir(temporaryDir);
  await fs.writeFile(join(temporaryDir, MARKER_FILE), "");
  // Keeps the directory out of git while it exists.
  await fs.writeFile(join(temporaryDir, ".gitignore"), "*\n");

  const entries = await fs.readdir(configDir, { withFileTypes: true });
  for (const entry of entries) {
    if (isMainFile(entry.name) || entry.name === ".gitignore") {
      continue;
    }
    const target = join(configDir, entry.name);
    const isDirectory = (await fs.stat(target)).isDirectory();
    await linkEntry(target, join(temporaryDir, entry.name), isDirectory);
  }

  await fs.writeFile(
    join(temporaryDir, "main.mjs"),
    createWrapperMain({ ...options, mainFile }),
  );
  return temporaryDir;
};

/**
 * Deletes a temporary config directory. A directory that the temporary mode did not
 * write (no marker file) is left alone and reported as an error.
 */
export const removeTemporaryConfigDir = async (temporaryDir: string): Promise<void> => {
  try {
    await fs.access(temporaryDir);
  } catch {
    return;
  }
  try {
    await fs.access(join(temporaryDir, MARKER_FILE));
  } catch {
    throw new Error(
      `${temporaryDir} already exists and was not written by the temporary mode. Move it away and try again.`,
    );
  }
  // Links are removed without touching the files they point to.
  await fs.rm(temporaryDir, { force: true, recursive: true });
};
